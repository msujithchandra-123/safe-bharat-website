export function getEquipmentItem(slug: string): EquipmentItem | undefined {
  return equipment.find((e) => e.slug === slug);
}

export function getEquipmentCategory(slug: string): EquipmentCategory | undefined {
  return equipmentCategories.find((c) => c.slug === slug);
}

export function getEquipmentByCategory(category: string): EquipmentItem[] {
  return equipment.filter((e) => e.category === category);
}
