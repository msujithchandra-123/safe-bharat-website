/**
 * Content files reference icons by name so that data stays serialisable and
 * can cross the server/client boundary.
 */
const icons = {
  badgeCheck: BadgeCheck,
  bell: Bell,
  bellRing: BellRing,
  bookOpen: BookOpen,
  building: Building2,
  calendarCheck: CalendarCheck,
  clipboardCheck: ClipboardCheck,
  clipboardList: ClipboardList,
  cog: Cog,
  construction: Construction,
  droplets: Droplets,
  factory: Factory,
  fileText: FileText,
  fireExtinguisher: FireExtinguisher,
  flame: Flame,
  flask: FlaskConical,
  gauge: Gauge,
  graduationCap: GraduationCap,
  hardHat: HardHat,
  headset: Headset,
  layers: Layers,
  listChecks: ListChecks,
  megaphone: Megaphone,
  package: Package,
  pill: Pill,
  radio: Radio,
  route: Route,
  shieldCheck: ShieldCheck,
  showerHead: ShowerHead,
  signpost: Signpost,
  siren: Siren,
  truck: Truck,
  users: Users,
  warehouse: Warehouse,
  workflow: Workflow,
  wrench: Wrench,
} satisfies Record<string, LucideIcon>;

export type IconName = keyof typeof icons;

export function Icon({ name, ...props }: { name: IconName } & LucideProps) {
  const Component = icons[name];
  return <Component aria-hidden="true" focusable="false" {...props} />;
}
